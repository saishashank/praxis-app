// V2-I5 / D-797: one index of the V2 decisions. Greps `- **D-nnn**` lines out of docs/M*_design.md
// (from D-206 on; D-001 to D-252 live in docs/07_decision_log.md) and writes docs/V2_decisions.md with
// one line per decision and the file that holds it. A duplicate id inside one file or across files is
// an error unless it is listed in KNOWN_REUSE (ids that two milestones used for different decisions).
//   node scripts/ci/decision-index.mjs          write the document
//   node scripts/ci/decision-index.mjs --check  exit 1 when the document is stale or an id is duplicated
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const FIRST = 206;
const MAX_LINE = 160;
/** Ids that more than one milestone design used for different decisions (recorded, not hidden). */
export const KNOWN_REUSE = new Set(
  /** @type {string[]} */ ([
    "D-377", // M15 (O4 offline setup simulation) and M16 (WP1 rework, proxy header) both took 377; neither is renumbered because both are cited
  ]),
);

const MILESTONE = (file) => file.replace(/^M/, "M").replace(/_design\.md$/, "");
const order = (m) => {
  const n = /^M(\d+)(?:\.(\d+))?(L)?/.exec(m);
  return n ? Number(n[1]) * 100 + Number(n[2] ?? 0) * 10 + (n[3] ? 1 : 0) : 9999;
};

export function oneLine(text) {
  const t = text.replace(/\*\*/g, "").replace(/`/g, "").replace(/\s+/g, " ").trim();
  // first sentence of 40+ characters whose quotes and brackets are balanced
  let s = t;
  for (const m of t.matchAll(/[.;:](?=\s+[A-Z(*]|$)/g)) {
    const head = t.slice(0, m.index + 1);
    const open = (head.match(/[([]/g) ?? []).length - (head.match(/[)\]]/g) ?? []).length;
    if (head.length >= 40 && open === 0 && (head.match(/"/g) ?? []).length % 2 === 0) {
      s = head;
      break;
    }
  }
  return (s.length > MAX_LINE ? `${s.slice(0, MAX_LINE - 3).trimEnd()}...` : s).replace(/\|/g, "/");
}

export function collect(root = ROOT) {
  const dir = path.join(root, "docs");
  const rows = [];
  for (const f of fs.readdirSync(dir).filter((x) => /^M[\d.]+L?_design\.md$/.test(x))) {
    const text = fs.readFileSync(path.join(dir, f), "utf8");
    for (const line of text.split("\n")) {
      const m =
        /^[-*]\s+\*\*D-(\d+)\*\*\s*(.*)$/.exec(line) ??
        /^\|\s*\*\*D-(\d+)\*\*\s*\|\s*(.*)$/.exec(line);
      if (!m) continue;
      const n = Number(m[1]);
      if (n < FIRST) continue;
      rows.push({ n, file: f, milestone: MILESTONE(f), text: oneLine(m[2]) });
    }
  }
  return rows;
}

export function duplicates(rows) {
  const seen = new Map();
  const dup = new Set();
  for (const r of rows) {
    if (seen.has(r.n)) dup.add(r.n);
    seen.set(r.n, r);
  }
  return [...dup].filter((n) => !KNOWN_REUSE.has(`D-${n}`)).sort((a, b) => a - b);
}

export function render(rows) {
  const by = new Map();
  for (const r of rows) {
    if (!by.has(r.milestone)) by.set(r.milestone, []);
    by.get(r.milestone).push(r);
  }
  const out = [
    "# V2 decision index",
    "",
    "<!-- Generated by scripts/ci/decision-index.mjs from docs/M*_design.md. Do not edit by hand. -->",
    "",
    'One line per V2 decision from D-206 on, grouped by milestone, with the file that holds the full text. D-001 to D-252 are in [07_decision_log.md](07_decision_log.md). Improvement-batch decisions are in the "Improvements" section at the end of `M13L_design.md`.',
    "",
  ];
  for (const m of [...by.keys()].sort((a, b) => order(a) - order(b) || a.localeCompare(b))) {
    const list = by.get(m).sort((a, b) => a.n - b.n);
    out.push(`## ${m} (${list[0].file})`, "", "| Id | Decision |", "| --- | --- |");
    for (const r of list) out.push(`| D-${r.n} | ${r.text} |`);
    out.push("");
  }
  return out.join("\n");
}

export function main(argv = process.argv.slice(2), root = ROOT) {
  const rows = collect(root);
  const dup = duplicates(rows);
  if (dup.length) {
    console.error(`decision-index: duplicate ids: ${dup.map((n) => `D-${n}`).join(", ")}`);
    return 1;
  }
  const text = render(rows);
  const file = path.join(root, "docs/V2_decisions.md");
  if (argv.includes("--check")) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (cur !== text) {
      console.error(
        "decision-index: docs/V2_decisions.md is stale; run node scripts/ci/decision-index.mjs",
      );
      return 1;
    }
    return 0;
  }
  fs.writeFileSync(file, text);
  console.log(`decision-index: wrote docs/V2_decisions.md (${rows.length} decisions)`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main();
}
