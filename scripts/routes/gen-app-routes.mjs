// Generator for src/lib/http/appRoutes.generated.ts (M21 A2, D-1210, UXN-324 b).
// The proxy marks a signed-in request for an UNKNOWN path exactly like a hidden one, so a hidden route and a
// missing route answer identically. "Known" = every src/app page.tsx and route.ts pattern (route groups and
// parallel slots removed), the metadata routes (robots, sitemap, manifest, icons), and every file under public/.
// It also writes EXPORT_ROUTES: the route handlers whose source sets Content-Disposition (SEC-014 export limit).
//   node scripts/routes/gen-app-routes.mjs --write   rewrite the generated module
//   node scripts/routes/gen-app-routes.mjs --check   exit 1 when the module is not what a fresh scan writes
// Every task that adds a page, a route handler or a public file re-runs --write.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(here, "..", "..");
export const OUT = "src/lib/http/appRoutes.generated.ts";

const PAGE = /^page\.(tsx|ts|jsx|js)$/;
const ROUTE = /^route\.(tsx|ts|jsx|js)$/;
const META = new Map([
  [/^robots\.(ts|js)$/, "robots.txt"],
  [/^sitemap\.(ts|js)$/, "sitemap.xml"],
  [/^manifest\.(ts|js)$/, "manifest.webmanifest"],
]);
const IMAGE_META =
  /^(icon|apple-icon|favicon|opengraph-image|twitter-image)\.(png|jpg|jpeg|gif|svg|ico)$/;

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const isGroup = (s) => s.startsWith("(") && s.endsWith(")");
const isSlot = (s) => s.startsWith("@");

/** The URL directory of a file under src/app, or null when it is not an address (a parallel slot). */
function urlDir(relDir) {
  const segs = relDir.split("/").filter(Boolean);
  if (segs.some(isSlot)) return null; // @modal and friends are overlays, not addresses of their own
  return "/" + segs.filter((s) => !isGroup(s)).join("/");
}
const join = (dir, name) => (dir === "/" ? "/" + name : dir + "/" + name);

export function scanRoutes(root = ROOT) {
  const appDir = path.join(root, "src", "app");
  const patterns = new Set();
  const exportRoutes = new Set();
  for (const full of walk(appDir)) {
    const rel = path.relative(appDir, full).split(path.sep).join("/");
    const name = path.posix.basename(rel);
    const dirRel = path.posix.dirname(rel) === "." ? "" : path.posix.dirname(rel);
    const dir = urlDir(dirRel);
    if (dir === null) continue;
    if (PAGE.test(name)) patterns.add(dir);
    else if (ROUTE.test(name)) {
      patterns.add(dir);
      if (/Content-Disposition/i.test(fs.readFileSync(full, "utf8"))) exportRoutes.add(dir);
    } else {
      for (const [re, url] of META) if (re.test(name)) patterns.add(join(dir, url));
      if (IMAGE_META.test(name)) patterns.add(join(dir, name));
    }
  }
  const pub = path.join(root, "public");
  for (const full of walk(pub)) {
    patterns.add("/" + path.relative(pub, full).split(path.sep).join("/"));
  }
  return { patterns: [...patterns].sort(), exportRoutes: [...exportRoutes].sort() };
}

export async function render(root = ROOT) {
  const { patterns, exportRoutes } = scanRoutes(root);
  const list = (a) => `[${a.map((s) => JSON.stringify(s)).join(", ")}]`;
  const src = `// GENERATED by scripts/routes/gen-app-routes.mjs (M21 A2, D-1210). Do not edit: run
// \`node scripts/routes/gen-app-routes.mjs --write\` after adding a page, a route handler or a public file.
// tests/http/appRoutes.test.ts fails when this file differs from a fresh scan.

/** Every address the app serves: page and route patterns ([x], [...x], [[...x]]), metadata routes, public files. */
export const KNOWN_ROUTE_PATTERNS: readonly string[] = ${list(patterns)};

/** Route handlers that set Content-Disposition: they take the SEC-014 export rate limit. */
export const GENERATED_EXPORT_ROUTES: readonly string[] = ${list(exportRoutes)};
`;
  const cfg = (await prettier.resolveConfig(path.join(root, OUT))) ?? {};
  return prettier.format(src, { ...cfg, filepath: path.join(root, OUT) });
}

async function main() {
  const mode = process.argv[2];
  if (mode !== "--write" && mode !== "--check") {
    console.error("usage: node scripts/routes/gen-app-routes.mjs --write | --check");
    process.exit(2);
  }
  const want = await render();
  const file = path.join(ROOT, OUT);
  const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (mode === "--write") {
    if (have !== want) fs.writeFileSync(file, want);
    console.log(have === want ? `${OUT} is up to date` : `${OUT} written`);
    return;
  }
  if (have !== want) {
    console.error(`${OUT} is stale: run node scripts/routes/gen-app-routes.mjs --write`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await main();
