/** The rule-set tables a halt model selects (ARN-117, CXA-002 f). */
const HALT_MODEL_TABLES = Object.freeze({
  in_bands: Object.freeze(["price_band", "surveillance_list"]),
  us_luld: Object.freeze(["trading_halt"]),
});

/**
 * The table names the schema hash covers for a market profile: the base list, plus the tables of the market's rule
 * sets (in_bands: price_band and surveillance_list; us_luld: trading_halt; announcement_category when the profile
 * has a category map other than `none`), sorted and without duplicates. AU (cx16, no map) is the base list.
 * @param {{ haltModel?: string | null, fields?: Record<string, { value?: unknown }> } | null | undefined} profile
 * @returns {string[]}
 */
export function stageTablesFor(profile) {
  const extra = [];
  const halt = profile?.haltModel;
  if (typeof halt === "string" && Object.prototype.hasOwnProperty.call(HALT_MODEL_TABLES, halt))
    extra.push(...HALT_MODEL_TABLES[halt]);
  const map = profile?.fields?.category_map?.value;
  if (
    map !== null &&
    typeof map === "object" &&
    map.kind !== "none" &&
    typeof map.kind === "string"
  )
    extra.push("announcement_category");
  if (extra.length === 0) return [...STAGE_TABLES];
  return [...new Set([...STAGE_TABLES, ...extra])].sort();
}
